r"""Write report/numbers.tex: every number the report prints, as a TeX key defined from tracked result files.

    python -m report.make_numbers [--root REPO] [--out FILE] [--check]

The report text says \num{e7w.bits.w64}, never 0.188. numbers.tex defines \num so that an unknown key is a LaTeX error (the report gate reads it from
the log), never a silent blank. Keys are lower-case words, digits and dots (e4.cap.w64.b1000); values are plain text without TeX syntax.

Reads only tracked files: the derived files in phonebook/results (including the four cells files), the E4, E6 and E7 protocol.json files, the capacity
books and their three control books, the 126 evaluation files, and the three E7 arm W width-64 metrics.csv files (for the dips). Anything missing, not a
whole number where a count is expected, or inconsistent between files stops the run with a NumbersError; nothing is ever printed as 0 or left blank.
The output is deterministic: sorted keys, LF line ends, no timestamp.

Exit status: 0 written (or, with --check, up to date); 1 with --check and the file differs or is missing; 2 an input is missing or wrong.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

from report import build_report as br

ROOT = Path(__file__).resolve().parents[1]
RESULTS = "phonebook/results"
EXPERIMENTS = "phonebook/experiments"
WIDTHS = (8, 16, 32, 64)
WIDE = (16, 32, 64)
SEEDS = (1, 2, 3)
WINDOW_FIRST, WINDOW_LAST = 3001, 4000   # the late window of E6 and E7: epochs 3001 to 4000
LAST_WINDOW = 100      # logged epochs in the late window (every 10 epochs)
HOLD_MIN = 50          # "holds": at least this many of the last 100 logged epochs (3001 to 4000) at 100%
SETTLED_RUN = 50       # "settled": this many consecutive logged epochs at 100% (500 epochs)
PASS_MIN = 2           # a rung passes at a budget when at least this many of its 3 book seeds are perfect by then
EARLY_KEY, LATE_KEY = "1001_2000", f"{WINDOW_FIRST}_{WINDOW_LAST}"   # the keys of the extension files' mean accuracies and epochs at 100%
E4_BUDGETS = ("100", "300", "500", "1000")   # epochs at which E4 reads its capacities (prefixes of one 1000-epoch run)
FIRST_CODE = 200       # the first area code and the first exchange (a phone number is AAA-EEE-SSSS)
AREA_CODES, EXCHANGES, SUBSCRIBERS = 800, 800, 10_000   # the phone-number space: area codes 200 to 999, exchanges 200 to 999, subscriber numbers 0000 to 9999
_ENTRY = re.compile(r"[A-Za-z]+ [A-Za-z]+=([0-9]{3})-([0-9]{3})-([0-9]{4})")
KEY = re.compile(r"[a-z][a-z0-9]*(?:\.[a-z0-9]+)*")
VALUE = re.compile(r"[A-Za-z0-9.,]+")


def bits_per_entry() -> float:
    """The information in the phone number only (the name is the prompt): log2 of the number of possible phone numbers."""
    return math.log2(AREA_CODES * EXCHANGES * SUBSCRIBERS)


class NumbersError(Exception):
    """An input is missing, malformed or inconsistent; the numbers file must not be written."""


# ---- rendering and use in the report ----------------------------------------------------------------------------------------------------------
HEADER = r"""% Generated by report/make_numbers.py from tracked result files. Do not edit; regenerate with: python -m report.make_numbers
\newcommand{\reportnumdef}[2]{\expandafter\def\csname num@#1\endcsname{#2}}
\newcommand{\num}[1]{\ifcsname num@#1\endcsname\csname num@#1\endcsname\else\PackageError{numbers}{Undefined number key `#1'}{Add the key to report/make_numbers.py and regenerate numbers.tex}\fi}
"""


def render(values: dict[str, str]) -> str:
    for key, value in values.items():
        if not KEY.fullmatch(key):
            raise NumbersError(f"bad key {key!r}: use lower-case letters, digits and dots, starting with a letter")
        if not VALUE.fullmatch(value):
            raise NumbersError(f"bad value {value!r} for {key}: only letters, digits, dots and commas")
    return HEADER + "".join(f"\\reportnumdef{{{key}}}{{{values[key]}}}\n" for key in sorted(values))


def num_uses(tex: str) -> list[str]:
    r"""The keys of every \num{...} in the source, in order, comments ignored."""
    return re.findall(r"\\num\{([^{}]*)\}", br.strip_comments(tex))


def undefined_keys(tex: str, values: dict[str, str]) -> list[str]:
    return [key for key in num_uses(tex) if key not in values]


def unused_keys(tex: str, values: dict[str, str]) -> list[str]:
    used = set(num_uses(tex))
    return sorted(key for key in values if key not in used)


COMMAND_ARGUMENTS = re.compile(
    r"\\(?:[cC]ite[a-zA-Z]*\*?|[a-zA-Z]*ref|label|includegraphics|input|include|bibliography|bibliographystyle|begin|end|num)"
    r"\s*(?:\[[^\]]*\]\s*)*\{[^{}]*\}"
)
_LITERAL = re.compile(r"(?<![\w.])(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?(?![\w])")


def typed_numbers_matching(tex: str, values: dict[str, str]) -> list[str]:
    """Number literals typed in the prose that equal a generated value (commas ignored), in order.

    Small whole numbers (one or two digits, no decimal point) are structure, not results ("width 8", "2 layers") and are never reported.
    Arguments of citation, reference, label, input and environment commands, and comments, are not prose.
    """
    known = {value.replace(",", "") for value in values.values()}
    return [literal for literal in typed_numbers(tex) if literal.replace(",", "") in known]


def typed_numbers(tex: str) -> list[str]:
    """Every number literal of three or more digits, or with a decimal point, typed in the prose, as typed and in order (the same prose rules)."""
    body = COMMAND_ARGUMENTS.sub(" ", br.strip_comments(tex))
    return [match.group(0) for match in _LITERAL.finditer(body) if "." in match.group(0) or sum(c.isdigit() for c in match.group(0)) >= 3]


# ---- reading the inputs -------------------------------------------------------------------------------------------------------------------------
class _Source:
    """One parsed JSON file with checked accessors; every error names the file and the path."""

    def __init__(self, name: str, data):
        self.name, self.data = name, data

    def at(self, *path):
        node = self.data
        for step in path:
            try:
                node = node[step]
            except (KeyError, IndexError, TypeError):
                raise NumbersError(f"{self.name}: no value at {'/'.join(map(str, path))}") from None
        return node

    def _bad(self, path, want, value) -> NumbersError:
        return NumbersError(f"{self.name}: {'/'.join(map(str, path))} must be {want}, got {value!r}")

    def count(self, *path) -> int:
        value = self.at(*path)
        if type(value) is not int or value < 0:
            raise self._bad(path, "a whole number of at least 0", value)
        return value

    def count_or_none(self, *path):
        value = self.at(*path)
        return None if value is None else self.count(*path)

    def real(self, *path, low: float = 0.0, high: float = math.inf) -> float:
        value = self.at(*path)
        if type(value) not in (int, float) or not math.isfinite(value) or not low <= value <= high:
            raise self._bad(path, f"a number from {low} to {high}", value)
        return float(value)

    def flag(self, *path) -> bool:
        value = self.at(*path)
        if type(value) is not bool:
            raise self._bad(path, "true or false", value)
        return value

    def choice(self, *path, allowed: tuple[str, ...]) -> str:
        value = self.at(*path)
        if value not in allowed:
            raise self._bad(path, f"one of {allowed}", value)
        return value


def _text(root: Path, rel: str) -> str:
    path = root / rel
    if not path.is_file():
        raise NumbersError(f"missing input file: {rel}")
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise NumbersError(f"cannot read {rel}: {error}") from error


def _json(root: Path, rel: str) -> _Source:
    try:
        return _Source(rel, json.loads(_text(root, rel)))
    except ValueError as error:
        raise NumbersError(f"{rel} is not valid JSON: {error}") from error


def _csv(root: Path, rel: str) -> list[dict[str, str]]:
    return list(csv.DictReader(_text(root, rel).splitlines()))


def _whole(row: dict[str, str], column: str, rel: str) -> int:
    try:
        value = int(row[column])
    except (KeyError, TypeError, ValueError):
        raise NumbersError(f"{rel}: column {column!r} must hold whole numbers, got {row.get(column)!r}") from None
    if value < 0:
        raise NumbersError(f"{rel}: column {column!r} must not be negative, got {value}")
    return value


def _word(value) -> str:
    return "none" if value is None else str(value)


def _mean(source: _Source, d: int) -> tuple[str, str]:
    return (f"{source.real(str(d), 'mean_accuracy', EARLY_KEY, high=1.0):.4f}", f"{source.real(str(d), 'mean_accuracy', LATE_KEY, high=1.0):.4f}")


def _recalled(acc: str, n: int, rel: str) -> int:
    """Entries recalled from a logged sequence accuracy (four decimals): it must be a whole number of entries within the rounding."""
    try:
        entries = float(acc) * n
    except ValueError:
        raise NumbersError(f"{rel}: Train Seq Acc must be a number, got {acc!r}") from None
    if not math.isfinite(entries):
        raise NumbersError(f"{rel}: Train Seq Acc must be a finite number, got {acc!r}")
    if abs(entries - round(entries)) > 0.05 or not 0 <= round(entries) <= n:
        raise NumbersError(f"{rel}: Train Seq Acc {acc} is not a whole number of {n} entries")
    return int(round(entries))


def _every_logged_epoch(epochs: list[int], step: int, last: int, rel: str, what: str) -> None:
    if sorted(epochs) != list(range(step, last + 1, step)):
        raise NumbersError(f"{rel}: {what} must have exactly one row for every logged epoch ({step}, {2 * step}, ... {last})")


def _dip_min(root: Path, seed: int, n: int, step: int, last: int):
    """The fewest entries recalled after the run first sat at 100% for SETTLED_RUN consecutive logged epochs; None if it never dipped."""
    rel = f"{EXPERIMENTS}/week_2026-11-13/e7_w_d64_seed{seed}/s{seed}_n640/d64/metrics.csv"
    rows = [(_whole(r, "Epoch", rel), _recalled(r.get("Train Seq Acc", ""), n, rel)) for r in _csv(root, rel)]
    _every_logged_epoch([e for e, _ in rows], step, last, rel, "the metrics file")
    rows.sort()
    run = 0
    for i, (_, recalled) in enumerate(rows):
        run = run + 1 if recalled == n else 0
        if run == SETTLED_RUN:
            settled = rows[i - SETTLED_RUN + 1][0]
            later = [k for e, k in rows if e > settled and k < n]
            return min(later) if later else None
    return None


def _protocols(root: Path, week: str, pattern: str) -> list[tuple[str, dict]]:
    found = [p for p in sorted((root / EXPERIMENTS / week).glob(f"{pattern}/protocol.json")) if "__interrupted" not in p.parts[-2]]
    if not found:
        raise NumbersError(f"no protocol.json files for {week}/{pattern}")
    out = []
    for path in found:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise NumbersError(f"cannot read {path.parts[-2]}/protocol.json: {error}") from error
        if not isinstance(data, dict) or not isinstance(data.get("runs"), list) or not data["runs"] or not all(isinstance(r, dict) for r in data["runs"]):
            raise NumbersError(f"{path.parts[-2]}/protocol.json: no list of runs")
        out.append((path.parts[-2], data))
    return out


def _unique(values, what: str) -> str:
    values = list(values)
    if any(v is None for v in values):
        raise NumbersError(f"protocols do not all record {what}")
    distinct = {str(v) for v in values}
    if len(distinct) != 1:
        raise NumbersError(f"protocols disagree about {what}: {sorted(distinct)}")
    return distinct.pop()


def _runs(protocols: list[tuple[str, dict]]) -> list[dict]:
    return [run for _, protocol in protocols for run in protocol["runs"]]


def _design(root: Path, out: dict[str, str]) -> dict[int, int]:
    """Design constants from the protocols; returns {rung size: updates per epoch}."""
    p4 = _protocols(root, "week_2026-10-31", "e4_*")
    p6 = _protocols(root, "week_2026-10-31", "e6_*")
    pw = _protocols(root, "week_2026-11-13", "e7_w_*")
    ps = _protocols(root, "week_2026-11-13", "e7_s_*")
    everything = p4 + p6 + pw + ps
    runs = _runs(everything)
    out["design.batch"] = _unique((r.get("batch_size") for r in runs), "batch_size")
    out["design.lr"] = _unique((r.get("lr") for r in runs), "lr")
    out["design.layers"] = _unique((r.get("model", {}).get("n_layers") for r in runs), "n_layers")
    out["design.heads"] = _unique((r.get("model", {}).get("n_heads") for r in runs), "n_heads")
    out["design.loginterval"] = _unique((r.get("accuracy_interval") for r in runs), "accuracy_interval")
    out["design.clip"] = _unique((p.get("optimizer", {}).get("grad_clip") for _, p in everything), "grad_clip")
    out["design.wd.default"] = _unique((p.get("optimizer", {}).get("weight_decay") for _, p in everything), "optimizer weight_decay")
    out["design.wd.w"] = _unique((r.get("weight_decay") for r in _runs(pw)), "weight_decay of the arm W runs")
    out["design.epochs.e4"] = _unique((r.get("epochs") for r in _runs(p4)), "E4 epochs")
    out["design.epochs.e6"] = _unique((r.get("epochs") for r in _runs(p6 + pw + ps)), "E6 and E7 epochs")
    kind, step, factor = _unique((r.get("lr_schedule") for r in _runs(ps)), "lr_schedule of the arm S runs").split(":")
    if kind != "step":
        raise NumbersError(f"arm S lr_schedule is not a step schedule: {kind!r}")
    out["design.s.step"], out["design.s.factor"] = step, factor
    out["design.bitsentry"] = f"{bits_per_entry():.3f}"
    upe: dict[int, set[int]] = defaultdict(set)
    for run in runs:
        try:
            upe[int(run["n_train"])].add(int(run["updates_per_epoch"]))
        except (KeyError, TypeError, ValueError):
            raise NumbersError(f"a protocol run does not record n_train and updates_per_epoch as whole numbers: {run.get('id')!r}") from None
    for n, seen in sorted(upe.items()):
        if len(seen) != 1:
            raise NumbersError(f"protocols disagree about updates_per_epoch for {n} entries: {sorted(seen)}")
    sizes = {len([line for line in _text(root, f"phonebook/inputs/capacity_seed{s}_control.txt").split("\n") if line.strip()]) for s in SEEDS}
    if len(sizes) != 1:
        raise NumbersError(f"the control books differ in size: {sorted(sizes)}")
    out["design.control"] = str(sizes.pop())
    result = {n: seen.pop() for n, seen in upe.items()}
    for n in sorted(result):
        out[f"design.upe.n{n}"] = str(result[n])
    interval, last = int(out["design.loginterval"]), int(out["design.epochs.e6"])
    if WINDOW_LAST != last:
        raise NumbersError(f"the late window ends at epoch {WINDOW_LAST} but E6 and E7 train for {last} epochs")
    window, remainder = divmod(WINDOW_LAST - WINDOW_FIRST + 1, interval)
    if remainder or window != LAST_WINDOW:
        raise NumbersError(f"the late window {WINDOW_FIRST} to {WINDOW_LAST} holds {window} logged epochs at every {interval}, but LAST_WINDOW is {LAST_WINDOW}")
    out["design.hold.min"], out["design.hold.window"], out["design.hold.from"] = str(HOLD_MIN), str(LAST_WINDOW), str(WINDOW_FIRST)
    out["design.settled.logged"], out["design.settled.epochs"] = str(SETTLED_RUN), str(SETTLED_RUN * interval)
    out["design.rule.min"] = str(PASS_MIN)
    out["design.phone.area"], out["design.phone.exchange"], out["design.phone.subscriber"] = str(AREA_CODES), str(EXCHANGES), f"{SUBSCRIBERS:,}"
    rungs = sorted(result)
    ratios = _ratios(rungs)
    _books(root, rungs)
    out["design.rung.first"], out["design.rung.last"], out["design.rung.count"] = str(rungs[0]), str(rungs[-1]), str(len(rungs))
    out["design.rung.ratio.min"], out["design.rung.ratio.max"] = f"{min(ratios):.2f}", f"{max(ratios):.2f}"
    _controls(root, out, {"e4": len(_runs(p4)), "e6": len(_runs(p6)), "e7w": len(_runs(pw)), "e7s": len(_runs(ps))})
    agree, compared = _regenerated(root, [("week_2026-10-31", p4 + p6), ("week_2026-11-13", pw + ps)])
    out["design.regen.agree"], out["design.regen.runs"] = str(agree), str(compared)
    return result


def _ratios(rungs: list[int]) -> list[float]:
    """The ratio of each rung to the one below it; a ladder has at least two rungs."""
    if len(rungs) < 2:
        raise NumbersError(f"the protocols have {len(rungs)} rungs, at least 2 are needed for a ladder")
    return [b / a for a, b in zip(rungs, rungs[1:])]


def _next_rung(ladder: list[int], n: int) -> str:
    """The smallest rung above n on the ladder, or "none" at the top; n must itself be a rung."""
    if n not in ladder:
        raise NumbersError(f"{n} is not a rung of the ladder {ladder}")
    return _word(next((rung for rung in ladder if rung > n), None))


def _books(root: Path, rungs: list[int]) -> None:
    """The capacity books agree with the protocols and with the phone-number constants: the sizes on disk are the rungs of the protocols for every book seed,
    and the largest book has that many entries, each a two-word name and a number AAA-EEE-SSSS inside the documented space."""
    largest = rungs[-1]
    inputs = root / "phonebook" / "inputs"
    for s in SEEDS:
        on_disk = sorted(int(m.group(1)) for p in inputs.glob(f"capacity_seed{s}_n*.txt") if (m := re.fullmatch(rf"capacity_seed{s}_n(\d+)\.txt", p.name)))
        if on_disk != rungs:
            raise NumbersError(f"the capacity books for seed {s} have rungs {on_disk}, the protocols have {rungs}")
        rel = f"phonebook/inputs/capacity_seed{s}_n{largest}.txt"
        lines = [line for line in _text(root, rel).split("\n") if line.strip()]   # read_text has turned Windows line endings into newlines
        if len(lines) != largest:
            raise NumbersError(f"{rel}: {len(lines)} entries, expected {largest}")
        for number, line in enumerate(lines, 1):
            match = _ENTRY.fullmatch(line)
            ok = match is not None and FIRST_CODE <= int(match.group(1)) < FIRST_CODE + AREA_CODES and FIRST_CODE <= int(match.group(2)) < FIRST_CODE + EXCHANGES \
                and int(match.group(3)) < SUBSCRIBERS
            if not ok:
                raise NumbersError(f"{rel}: line {number} is not 'Name Name=NNN-NNN-NNNN' with the area code from {FIRST_CODE} to {FIRST_CODE + AREA_CODES - 1} "
                                   f"and the exchange from {FIRST_CODE} to {FIRST_CODE + EXCHANGES - 1} and a subscriber number below {SUBSCRIBERS}: {line!r}")


def _controls(root: Path, out: dict[str, str], runs: dict[str, int]) -> None:
    """The control results of every run: the cells files have one row per run, every control passed, and the most control entries recalled in any run."""
    worst = total = 0
    for name, expected in runs.items():
        rel = f"{RESULTS}/{name}_cells.csv"
        rows = _csv(root, rel)
        if len(rows) != expected:
            raise NumbersError(f"{rel}: {len(rows)} rows but the protocols have {expected} runs")
        for row in rows:
            if row.get("control_ok") != "True":
                raise NumbersError(f"{rel}: control_ok must be True in every row, got {row.get('control_ok')!r}")
            worst = max(worst, _whole(row, "max_control", rel))
        total += len(rows)
    out["design.control.max"], out["design.control.runs"] = str(worst), str(total)
    out["design.runs.e4"], out["design.runs.e6"], out["design.runs.e7"] = str(runs["e4"]), str(runs["e6"]), str(runs["e7w"] + runs["e7s"])


def _regenerated(root: Path, groups: list[tuple[str, list[tuple[str, dict]]]]) -> tuple[int, int]:
    """(runs whose regenerated answers equal the teacher-forced count, runs compared): the evaluation of the saved weights of every run."""
    agree = total = 0
    for week, protocols in groups:
        for folder, protocol in protocols:
            for run in protocol["runs"]:
                book = _json(root, f"{EXPERIMENTS}/{week}/{folder}/{run['scenario']}/{run['condition']}.evaluation.json")
                forced = (book.count("books", "A", "teacher_forced", "sequence_correct"), book.count("books", "A", "teacher_forced", "sequence_total"))
                generated = (book.count("books", "A", "generation", "correct"), book.count("books", "A", "generation", "total"))
                total += 1
                agree += forced == generated
    return agree, total


def _scores(root: Path, name: str) -> list[str]:
    rows = _json(root, f"{RESULTS}/{name}").data
    if not isinstance(rows, list) or not all(isinstance(r, dict) and isinstance(r.get("result"), str) for r in rows):
        raise NumbersError(f"{name}: expected a list of rows that each have a text 'result'")
    return [r["result"] for r in rows]


def build(root: Path | str = ROOT) -> dict[str, str]:
    """Every number of the report, as {key: text}; raises NumbersError if anything is missing or inconsistent."""
    root = Path(root)
    out: dict[str, str] = {}
    upe = _design(root, out)

    # E4
    e4 = _json(root, f"{RESULTS}/e4_capacity.json")
    for d in WIDTHS:
        budgets = e4.at(str(d), "capacity_by_budget")
        if not isinstance(budgets, dict) or sorted(budgets) != sorted(E4_BUDGETS):
            raise NumbersError(f"{e4.name}: the budgets must be {list(E4_BUDGETS)}, got {sorted(budgets) if isinstance(budgets, dict) else budgets!r}")
    for i, budget in enumerate(E4_BUDGETS, 1):
        out[f"design.budget.{i}"] = budget
    for d in WIDTHS:
        w = str(d)
        for budget in E4_BUDGETS:
            out[f"e4.cap.w{d}.b{budget}"] = _word(e4.count_or_none(w, "capacity_by_budget", budget))
        cap = e4.count(w, "capacity_by_budget", "1000")
        out[f"e4.params.w{d}"] = f"{e4.count(w, 'params'):,}"
        out[f"e4.bits.w{d}"] = f"{e4.real(w, 'bits_per_param_at_largest_budget'):.3f}"
        out[f"e4.boundary.w{d}"] = e4.choice(w, "boundary", allowed=("stable", "moving"))
        if cap not in upe:
            raise NumbersError(f"no protocol has {cap} entries, so updates per epoch at the width {d} capacity are unknown")
        out[f"e4.upe.w{d}"] = str(upe[cap])
        out[f"e4.updates.w{d}"] = f"{upe[cap] * 1000:,}"

    # E6 curves: the logged epochs at 100%, the late window and the recall at epoch 4000, per run
    curves_rel = f"{RESULTS}/fig_e6_curves.csv"
    curves: dict[tuple[int, int], list[tuple[int, int]]] = defaultdict(list)
    entries: dict[int, set[int]] = defaultdict(set)
    for row in _csv(root, curves_rel):
        d, s, n = _whole(row, "model_d", curves_rel), _whole(row, "seed", curves_rel), _whole(row, "entries", curves_rel)
        recalled = _whole(row, "recalled", curves_rel)
        if recalled > n:
            raise NumbersError(f"{curves_rel}: {recalled} entries recalled of {n}")
        entries[d].add(n)
        curves[(d, s)].append((_whole(row, "epoch", curves_rel), recalled))

    arms = (
        ("e6", _json(root, f"{RESULTS}/e6_extension.json"), _json(root, f"{RESULTS}/e6_capacity.json"), WIDTHS),
        ("e7w", _json(root, f"{RESULTS}/e7w_extension.json"), _json(root, f"{RESULTS}/e7w_capacity.json"), WIDE),
        ("e7s", _json(root, f"{RESULTS}/e7s_extension.json"), _json(root, f"{RESULTS}/e7s_capacity.json"), WIDE),
    )
    for arm, ext, cap, widths in arms:
        holding_total = 0
        for d in widths:
            w = str(d)
            n = ext.count(w, "n")
            seeds = ext.count(w, "seeds")
            if seeds != len(SEEDS):
                raise NumbersError(f"{ext.name}: seeds must be {len(SEEDS)} (the keys cover book seeds {SEEDS[0]} to {SEEDS[-1]}), got {seeds}")
            perfect_by, reached, at_end = ext.count(w, "perfect_by", "4000"), ext.count(w, "reached_perfect"), ext.count(w, "perfect_at_end")
            passes, first_budget = ext.flag(w, "passes", "4000"), ext.count_or_none(w, "first_pass_budget")
            firsts = [ext.count_or_none(w, "first_perfect", str(s)) for s in SEEDS]
            if reached > seeds or perfect_by != reached:   # 4000 is the last logged epoch, so perfect by 4000 means reached 100% at some point
                raise NumbersError(f"{ext.name}: width {d}: reached_perfect {reached} and perfect_by {perfect_by} must be equal and at most {seeds}")
            if at_end > reached:
                raise NumbersError(f"{ext.name}: width {d}: perfect_at_end {at_end} exceeds reached_perfect {reached}")
            if sum(f is not None for f in firsts) != reached:
                raise NumbersError(f"{ext.name}: width {d}: first_perfect lists {sum(f is not None for f in firsts)} seeds that reached 100%, reached_perfect says {reached}")
            if passes != (perfect_by >= PASS_MIN):
                raise NumbersError(f"{ext.name}: width {d}: passes at 4000 is {passes} but {perfect_by} of {seeds} seeds were perfect by 4000 (a rung passes with {PASS_MIN})")
            if (first_budget is None) == passes:
                raise NumbersError(f"{ext.name}: width {d}: first_pass_budget {first_budget!r} does not agree with passes at 4000 ({passes})")
            out[f"{arm}.n.w{d}"] = str(n)
            out[f"{arm}.passes.w{d}"] = "yes" if passes else "no"
            out[f"{arm}.firstbudget.w{d}"] = _word(first_budget)
            out[f"{arm}.perfectby.w{d}"] = str(perfect_by)
            out[f"{arm}.reached.w{d}"] = str(reached)
            out[f"{arm}.atend.w{d}"] = str(at_end)
            out[f"{arm}.mean.w{d}.early"], out[f"{arm}.mean.w{d}.late"] = _mean(ext, d)
            bits = cap.at(w, "bits_per_param_at_largest_budget")
            out[f"{arm}.bits.w{d}"] = "none" if bits is None else f"{cap.real(w, 'bits_per_param_at_largest_budget'):.3f}"
            late = []
            for s, first in zip(SEEDS, firsts):
                out[f"{arm}.first.w{d}.s{s}"] = "never" if first is None else str(first)
                if arm == "e6":
                    run = curves.get((d, s))
                    if not run or entries[d] != {n}:
                        raise NumbersError(f"{curves_rel}: no curve for width {d} seed {s} with {n} entries")
                    _every_logged_epoch([e for e, _ in run], int(out["design.loginterval"]), int(out["design.epochs.e6"]), curves_rel, f"the curve of width {d} seed {s}")
                    late.append(sum(1 for e, k in run if WINDOW_FIRST <= e <= WINDOW_LAST and k == n))
                    out[f"e6.logged100.w{d}.s{s}"] = str(sum(1 for e, k in run if k == n))
                    at_end = [k for e, k in run if e == 4000]
                    if len(at_end) != 1:
                        raise NumbersError(f"{curves_rel}: width {d} seed {s} has {len(at_end)} rows at epoch 4000")
                    out[f"e6.recall4000.w{d}.s{s}"] = str(at_end[0])
                else:
                    late.append(ext.count(w, "epochs_at_100", "by_seed", str(s), LATE_KEY))
                    if late[-1] > LAST_WINDOW:
                        raise NumbersError(f"{ext.name}: {w}/epochs_at_100/by_seed/{s}/{LATE_KEY} is {late[-1]}, but the window holds {LAST_WINDOW} logged epochs")
                out[f"{arm}.late100.w{d}.s{s}"] = str(late[-1])
            holding = sum(1 for c in late if c >= HOLD_MIN)
            out[f"{arm}.holding.w{d}"] = str(holding)
            if d != 8:
                holding_total += holding
        out[f"{arm}.holdingtotal"] = str(holding_total)
    out["design.seeds"] = str(len(SEEDS))   # every extension file was checked to say so

    # the rung above each pass (the limit sentence: those rungs were not run at the longer budget) and the updates of the E6 rungs in 4000 epochs
    ladder = sorted(upe)
    for d in WIDE:
        nw, ns = out[f"e7w.n.w{d}"], out[f"e7s.n.w{d}"]
        if nw != ns:
            raise NumbersError(f"E7 arms W and S disagree about the rung at width {d}: {nw} and {ns}")
        out[f"e7.next.w{d}"] = _next_rung(ladder, int(nw))
    for d in WIDTHS:
        n6 = int(out[f"e6.n.w{d}"])
        if n6 not in upe:
            raise NumbersError(f"no protocol has {n6} entries, so updates per epoch at the E6 rung of width {d} are unknown")
        out[f"e6.next.w{d}"] = _next_rung(ladder, n6) if out[f"e6.passes.w{d}"] == "yes" else "none"
        out[f"e6.updates.w{d}"] = f"{upe[n6] * int(out['design.epochs.e6']):,}"

    # the dips of arm W at width 64 (the one place the report needs the raw per-epoch counts of E7)
    n64 = int(out["e7w.n.w64"])
    for s in SEEDS:
        out[f"e7w.dipmin.w64.s{s}"] = _word(_dip_min(root, s, n64, int(out["design.loginterval"]), int(out["design.epochs.e6"])))

    # prediction scores
    for prefix, name in (("e4", "e4_prediction_scores.json"), ("e6", "e6_prediction_scores.json"), ("e7", "e7_scores.json")):
        results = _scores(root, name)
        hits = sum(r.startswith("HIT") for r in results)
        exact = sum(r == "HIT (exact)" for r in results)
        misses = sum(r == "MISS" for r in results)
        out[f"{prefix}.pred.scored"], out[f"{prefix}.pred.hits"], out[f"{prefix}.pred.exact"] = str(hits + misses), str(hits), str(exact)
        if prefix == "e7":
            fired = sum(r == "TRIPWIRE FIRED" for r in results)
            out["e7.pred.inrange"], out["e7.pred.misses"] = str(hits - exact), str(misses)
            out["e7.tripwire.fired"] = str(fired)
            out["e7.tripwire.total"] = str(fired + sum(r == "TRIPWIRE NOT FIRED" for r in results))
    return dict(sorted(out.items()))


# ---- command line ----------------------------------------------------------------------------------------------------------------------------------
def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m report.make_numbers", description="Write report/numbers.tex from the tracked result files.")
    parser.add_argument("--root", type=Path, default=ROOT, help="the repository root (default: this repository)")
    parser.add_argument("--out", type=Path, help="the file to write (default: report/numbers.tex under the root)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if the file differs from what would be written")
    args = parser.parse_args(argv)
    out = args.out if args.out is not None else args.root / "report" / "numbers.tex"
    try:
        values = build(args.root)
        text = render(values).encode("utf-8")
    except NumbersError as error:
        print(f"numbers: {error}", file=sys.stderr)
        return 2
    try:
        if args.check:
            current = out.read_bytes().replace(b"\r\n", b"\n") if out.is_file() else None
            if current == text:
                print(f"{out}: up to date ({len(values)} numbers)")
                return 0
            print(f"{out} differs from what the generator writes now (or is missing); run: python -m report.make_numbers")
            return 1
        _write_atomically(out, text)
    except OSError as error:
        print(f"numbers: cannot use {out}: {error}", file=sys.stderr)
        return 2
    print(f"wrote {out} ({len(values)} numbers)")
    return 0


def _write_atomically(out: Path, data: bytes) -> None:
    """Write beside the target, then replace it, so a failure never leaves a truncated numbers.tex (or a stray temporary file)."""
    out.parent.mkdir(parents=True, exist_ok=True)
    temporary = out.with_name(out.name + ".tmp")
    try:
        temporary.write_bytes(data)
        os.replace(temporary, out)
    except OSError:
        temporary.unlink(missing_ok=True)
        raise


if __name__ == "__main__":
    sys.exit(main())
